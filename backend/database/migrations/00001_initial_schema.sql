    CONSTRAINT notifications_type_not_blank CHECK (btrim(type) <> ''),
    CONSTRAINT notification_message_not_blank CHECK (btrim(message) <> ''),
    CONSTRAINT notifications_data_is_object CHECK (jsonb_typeof(data) = 'object')
);

